-- ============================================================
-- 5. 回填订单的支付/入离时间与结算金额
--    房态推导与"近7天收入"统计依赖这些字段：
--      · 收入按 actual_check_out_time 归属，金额取 final_price
--      · 超时未支付自动取消依赖 pay_deadline
-- ============================================================

-- 5.1 已支付及之后状态的订单，支付时间以创建时间兜底
UPDATE `t_order` SET `paid_time` = `create_time`
 WHERE `status` IN (1, 2, 3) AND `paid_time` IS NULL;

-- 5.2 已退房订单：用入住登记记录里的真实时间回填，保证与 t_check_in 一致
UPDATE `t_order` o
  JOIN `t_check_in` c ON c.`order_id` = o.`id`
   SET o.`actual_check_in_time`  = c.`check_in_time`,
       o.`actual_check_out_time` = c.`check_out_time`,
       o.`final_price`           = c.`actual_price`
 WHERE o.`status` = 3;

-- 5.3 在住订单的实际入住时间
UPDATE `t_order` SET `actual_check_in_time` = TIMESTAMP(`check_in_date`, '14:00:00')
 WHERE `status` = 2 AND `actual_check_in_time` IS NULL;

-- 5.4 待支付订单：把创建时间与支付截止时间设成相对当前时刻，
--     让它们保持"刚下单、待支付"的真实状态；
--     否则这些订单会被"超时未支付自动取消"定时任务在启动后立刻清理掉，
--     演示数据就失去"待支付"这一状态了。
UPDATE `t_order`
   SET `create_time`  = DATE_SUB(NOW(), INTERVAL 5 MINUTE),
       `pay_deadline` = DATE_ADD(NOW(), INTERVAL 25 MINUTE)
 WHERE `status` = 0;

-- ============================================================
-- 6. 回填订单号序号表 t_seq
--    订单号格式：ORD + yyyyMMdd(位置4起8位) + 3位当日序号(位置12起)，
--    序号由 t_seq 原子自增产生。这里按已有订单回填，保证新增订单号不与历史冲突。
-- ============================================================
INSERT IGNORE INTO `t_seq` (`name`, `next_val`)
SELECT CONCAT('order_no_', SUBSTRING(`order_no`, 4, 8)) AS `seq_name`,
       MAX(CAST(SUBSTRING(`order_no`, 12) AS UNSIGNED))  AS `max_seq`
  FROM `t_order`
 WHERE `order_no` REGEXP '^ORD[0-9]{11}$'
 GROUP BY `seq_name`;

